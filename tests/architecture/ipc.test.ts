// L'IPC a un seul point d'entrée, et il est généré.
//
// V1 : 86 commandes et 17 events appelés par des chaînes de caractères, vérifiées nulle
// part — 9 bugs de noms de champs en une seule session. Et `withGlobalTauri` exposait
// `window.__TAURI__`, donc n'importe quel fichier pouvait appeler n'importe quoi, ce qui
// rendait `invoke` non mockable : 3 suites de tests ont fini skippées.
import { describe, expect, it } from 'vitest';
import { lire, sansCommentaires, sources } from './_lecture';
import { imports } from './regles-imports';

const CLIENT = 'src/ipc/client.ts';
const BINDINGS = 'src/ipc/bindings.ts';

describe('IPC', () => {
  it('seul src/ipc/ importe @tauri-apps/api', () => {
    const fautes = sources('src', ['.ts', '.svelte'])
      .filter(([f]) => !f.startsWith('src/ipc/'))
      .flatMap(([f, c]) => imports(c).filter((s) => s.startsWith('@tauri-apps/')).map((s) => `${f} → ${s}`));
    expect(fautes, `tout passe par ${CLIENT}`).toEqual([]);
  });

  it('personne n’utilise window.__TAURI__', () => {
    const fautes = sources('src', ['.ts', '.svelte'])
      .filter(([, c]) => sansCommentaires(c).includes('__TAURI__'))
      .map(([f]) => f);
    expect(fautes, 'withGlobalTauri est à false — il n’existe pas').toEqual([]);
  });

  it('les bindings sont générés, pas écrits à la main', () => {
    expect(lire(BINDINGS)).toContain('generated by Tauri Specta');
  });

  it('le détecteur voit bien le vrai import de Tauri, là où il est permis', () => {
    // La seconde question d'un détecteur : *est-ce que je reconnais la matière réelle ?*
    // Ici elle a du mordant, parce que **la seule matière du projet est générée**. Le
    // `@tauri-apps/api/core` de l'app ne vit pas dans `client.ts` — qui n'importe que
    // `./bindings` — mais dans `bindings.ts`, écrit par specta. Le jour où specta change
    // d'appel (`window.__TAURI_INTERNALS__` au lieu de l'import, par exemple), plus un seul
    // fichier du projet ne porte ce spécificateur : les deux interdictions ci-dessus
    // deviennent vraies sur un ensemble vide et restent vertes. Personne n'aurait décidé ce
    // changement — c'est le mode de panne exact qui a désarmé INV-06 en phase 2.
    const dans = sources('src/ipc', ['.ts']).flatMap(([f, c]) =>
      imports(c).filter((x) => x.startsWith('@tauri-apps/')).map((x) => `${f} → ${x}`),
    );
    expect(dans.length, 'src/ipc/ doit vraiment importer @tauri-apps').toBeGreaterThan(0);
  });
});
